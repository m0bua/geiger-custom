"""Check SPI alert pagination and lookahead using the compiled firmware.

Run python tools/build_firmware.py and then this script. The load fixture is
generated by tools/generate_fake_spi_fixture.py.
"""
from datetime import datetime, timedelta, timezone
from pathlib import Path
import struct
import sys

sys.dont_write_bytecode = True

from generate_fake_spi_fixture import Engine, NOW, append
from test_log_engine import request


class MeteredEngine(Engine):
    def __init__(self, image):
        self.spi_reads = 0
        super().__init__(mode=1, nor=image)

    def read_spi(self, args):
        self.spi_reads += 1
        return super().read_spi(args)


def open_image(image):
    firmware = MeteredEngine(image)
    firmware.now = int((NOW - datetime(2000, 1, 1, tzinfo=timezone.utc)).total_seconds())
    assert firmware.call("spi_log_init")
    firmware.spi_reads = 0
    return firmware


def read_pages(firmware, expected, date_limit=0, kind=3, period=60):
    cursor = (0xFFFFFFFF, 0xFFFF, 0)
    received = []
    more = True
    while more:
        payload = struct.pack("<BBIIHHI", kind, 5, period, *cursor, date_limit)
        response = request(firmware, 6, payload)
        assert response[0:2] == bytes((0, kind))
        count, more = response[2], bool(response[3])
        assert len(response) == 12 + count * 25
        cursor = struct.unpack_from("<IHH", response, 4)
        for index in range(count):
            time, pulses, _, _, _, epoch, _, identity = struct.unpack_from(
                "<5IHBH", response, 12 + index * 25)
            received.append((time, pulses, epoch, identity))
        assert count or not more
        assert len(received) <= len(expected)
    assert [(time, pulses) for time, pulses, _, _ in received] == expected
    assert len({(epoch, identity) for _, _, epoch, identity in received}) == len(expected)
    return firmware.spi_reads


def seconds(moment):
    return int((moment - datetime(2000, 1, 1, tzinfo=timezone.utc)).total_seconds())


def main():
    image = (Path(__file__).resolve().parents[1] /
             "tests/fixtures/spi-logs-load-500-each-1mb.bin").read_bytes()
    expected = [(seconds(NOW - timedelta(hours=(500 - index) * 12)),
                 36 + (index * 37) % 900) for index in reversed(range(500))]
    reads = read_pages(open_image(image), expected)
    assert reads < 2500, f"Unexpectedly many SPI reads for 500 alerts: {reads}"
    print(f"PASS: 500 alerts in 5-record pages, {reads} SPI reads")
    reads = read_pages(open_image(image), expected[100:], expected[100][0])
    assert reads < 2200, f"Unexpectedly many SPI reads with a date limit: {reads}"
    print(f"PASS: 400 alerts with an inclusive date limit, {reads} SPI reads")

    graph = open_image(image)
    graph.set("lcd_graph_log_type", 4)
    graph.call("lcd_graph_update_log_summary")
    assert graph.get("lcd_graph_log_available") == 50
    assert graph.call("lcd_graph_load_log_window", 0)
    visible = graph.get("lcd_graph_log_visible")
    assert visible == 13
    base = graph.symbols["lcd_graph_log_points"]
    actual = []
    for index in range(visible):
        row = bytes(graph.cpu.mem_read(base + index * 32, 32))
        actual.append((struct.unpack_from("<I", row, 0)[0],
                       struct.unpack_from("<I", row, 8)[0]))
    assert actual == expected[:visible]
    assert graph.spi_reads < 500, f"Unexpectedly many graph SPI reads: {graph.spi_reads}"
    print(f"PASS: alert graph summary and {visible} columns, {graph.spi_reads} SPI reads")

    for kind, period in ((0, 60), (1, 3600), (2, 86400)):
        reference = open_image(image).points(kind, period, limit=500)
        assert len(reference) == 500
        rows = [(point["time"], point["count"]) for point in reference]
        reads = read_pages(open_image(image), rows, kind=kind, period=period)
        print(f"PASS: log type {kind} paged records match sequential reads, {reads} SPI reads")

    firmware = open_image(b"\xff" * (1024 * 1024))
    start = datetime(2026, 10, 1, tzinfo=timezone.utc)
    events = []
    for index in range(289):
        moment = start + timedelta(minutes=index)
        append(firmware, 3, moment, 10 + index, 100, 0, 60)
        events.append((seconds(moment), 10 + index))
    for index in range(7):
        moment = start + timedelta(minutes=289)
        append(firmware, 3, moment, 100 + index, 100, 0, 60)
        events.append((seconds(moment), 100 + index))
    moment = start + timedelta(minutes=290)
    append(firmware, 3, moment, 999, 100, 0, 60)
    events.append((seconds(moment), 999))
    firmware.reset()
    assert firmware.call("spi_log_init")
    firmware.spi_reads = 0
    reads = read_pages(firmware, list(reversed(events)))
    assert reads < 2000, f"Unexpectedly many SPI reads around duplicate alerts: {reads}"
    print(f"PASS: duplicate timestamps across a sector and page boundary, {reads} SPI reads")


if __name__ == "__main__":
    main()
