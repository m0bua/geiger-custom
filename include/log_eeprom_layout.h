#ifndef LOG_EEPROM_LAYOUT_H
#define LOG_EEPROM_LAYOUT_H

#include <stdint.h>

/* EEPROM user settings and dose checkpoints occupy bytes 0..347. The logger
 * owns bytes 348..2047. */
#define LOG_EEPROM_REGION_BASE 348u
#define LOG_EEPROM_REGION_SIZE 1700u

#define LOG_EEPROM_MINUTE_COUNT 62u
#define LOG_EEPROM_HOUR_COUNT 25u
#define LOG_EEPROM_DAY_COUNT 50u
#define LOG_EEPROM_ALERT_COUNT 30u

#define LOG_EEPROM_RECORD_SIZE 9u
#define LOG_EEPROM_ALERT_SIZE 11u

#define LOG_EEPROM_MINUTE_BASE LOG_EEPROM_REGION_BASE
#define LOG_EEPROM_MINUTE_SIZE \
    (LOG_EEPROM_MINUTE_COUNT * LOG_EEPROM_RECORD_SIZE)
#define LOG_EEPROM_HOUR_BASE \
    (LOG_EEPROM_MINUTE_BASE + LOG_EEPROM_MINUTE_SIZE)
#define LOG_EEPROM_HOUR_SIZE \
    (LOG_EEPROM_HOUR_COUNT * LOG_EEPROM_RECORD_SIZE)
#define LOG_EEPROM_DAY_BASE \
    (LOG_EEPROM_HOUR_BASE + LOG_EEPROM_HOUR_SIZE)
#define LOG_EEPROM_DAY_SIZE \
    (LOG_EEPROM_DAY_COUNT * LOG_EEPROM_RECORD_SIZE)
#define LOG_EEPROM_ALERT_BASE \
    (LOG_EEPROM_DAY_BASE + LOG_EEPROM_DAY_SIZE)
#define LOG_EEPROM_ALERT_SIZE_BYTES \
    (LOG_EEPROM_ALERT_COUNT * LOG_EEPROM_ALERT_SIZE)
#define LOG_EEPROM_SERVICE_BASE \
    (LOG_EEPROM_REGION_BASE + LOG_EEPROM_REGION_SIZE - 114u)
#define LOG_EEPROM_SERVICE_SIZE \
    (LOG_EEPROM_REGION_BASE + LOG_EEPROM_REGION_SIZE - \
        LOG_EEPROM_SERVICE_BASE)

#define LOG_EEPROM_SEGMENT_TABLE_SIZE 64u
#define LOG_EEPROM_STATE_COPY_SIZE 15u
#define LOG_EEPROM_TRANSACTION_SIZE 16u
#define LOG_EEPROM_TABLE_CRC_SIZE 2u
#define LOG_EEPROM_SEGMENT_TABLE_BASE LOG_EEPROM_SERVICE_BASE
#define LOG_EEPROM_STATE_A_BASE \
    (LOG_EEPROM_SEGMENT_TABLE_BASE + LOG_EEPROM_SEGMENT_TABLE_SIZE)
#define LOG_EEPROM_STATE_B_BASE \
    (LOG_EEPROM_STATE_A_BASE + LOG_EEPROM_STATE_COPY_SIZE)
#define LOG_EEPROM_TRANSACTION_BASE \
    (LOG_EEPROM_STATE_B_BASE + LOG_EEPROM_STATE_COPY_SIZE)
#define LOG_EEPROM_TABLE_CRC_BASE \
    (LOG_EEPROM_TRANSACTION_BASE + LOG_EEPROM_TRANSACTION_SIZE)
#define LOG_EEPROM_METADATA_END \
    (LOG_EEPROM_TABLE_CRC_BASE + LOG_EEPROM_TABLE_CRC_SIZE)

_Static_assert(LOG_EEPROM_SERVICE_BASE >=
        LOG_EEPROM_ALERT_BASE + LOG_EEPROM_ALERT_SIZE_BYTES,
    "EEPROM logger records overlap the metadata area");
_Static_assert(LOG_EEPROM_SERVICE_SIZE == 114u,
    "EEPROM logger service area must remain 114 bytes");
_Static_assert(LOG_EEPROM_METADATA_END + 2u == 2048u,
    "EEPROM logger metadata must leave exactly two spare bytes");
_Static_assert(LOG_EEPROM_SERVICE_BASE + LOG_EEPROM_SERVICE_SIZE == 2048u,
    "EEPROM logger region must end at the 2 KiB boundary");

#endif
